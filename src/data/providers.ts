export const ALL_MODELS = PROVIDERS.flatMap((p) => p.models);

export function getProvider(id: ProviderId): ProviderInfo {
  return PROVIDERS.find((p) => p.id === id) || PROVIDERS[0];
}

export function getModel(providerId: ProviderId, modelId: string) {
  const provider = getProvider(providerId);
  const found = provider.models.find((m) => m.id === modelId);
  if (found) return found;
  if (providerId === 'custom') {
    return {
      id: modelId || 'custom-model',
      name: modelId || 'Custom Model',
      providerId: 'custom' as ProviderId,
      description: 'Custom user-defined model endpoint',
      contextWindow: 'Custom',
      tier: 'custom' as const,
      tierLabel: 'CUSTOM',
      tierDetails: 'User-configured custom endpoint',
      isFree: false,
      category: 'general' as const,
    };
  }
  return provider.models[0] || ALL_MODELS[0];
}
